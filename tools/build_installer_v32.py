#!/usr/bin/env python3
"""Idempotently embed exact B1 V3.2 firmware into audited WebInstaller source.
The source template can be regenerated by rerunning this script on the generated HTML.
"""
from pathlib import Path
import re,hashlib,base64
root=Path(__file__).resolve().parent.parent
p=root/'B1-WebInstaller.html'
fw=(root/'build/SikkenWorks-B1-V3.2-BEETLE-OTA.fwsc').read_bytes()
sha=hashlib.sha256(fw).hexdigest();s=p.read_text()
s=s.replace('B1 V3.1','B1 V3.2').replace('FM-1_2131','FM-1_2132')
s=re.sub(r"(HASH_ET: ')[0-9a-f]{64}(')",rf'\g<1>{sha}\2',s)
s=re.sub(r'(<script id="firmware-embedded" type="application/octet-stream">)\s*.*?\s*(</script>)',lambda m:m[1]+'\n'+base64.b64encode(fw).decode()+'\n'+m[2],s,flags=re.S)
p.write_text(s)
print('Installer',p,'embed SHA',sha,'bytes',len(fw))
