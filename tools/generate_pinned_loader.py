#!/usr/bin/env python3
"""Generate an exact byte-pinned 6,898-byte FM1 OTA loader from the audited BEETLE package.

Never accept a loader with an unreviewed SHA-256. This is an immutable
reference used for a strict byte-equality comparison *in addition to* the
package CRC and structure checks, avoiding an on-target SHA runtime dependency.
"""
from pathlib import Path
import hashlib, sys
sys.path.insert(0,str(Path(__file__).resolve().parent))
from fm1_fwsc import parse_ufw
REF_SHA='2b79c6bf29fa65adb6f061aae4dfea23e13b4abf3829c96aacaee1abbc1e55de'
BODY_SHA='d0b1a05c63030b58e5be06b93751e6cc375d3d34eec584109f97fd31f0a42a78'
root=Path(__file__).resolve().parent.parent
source=root/'build/BEETLE-RC1.01-RESTORE-ORIGINAL.fwsc'
assert hashlib.sha256(source.read_bytes()).hexdigest()==REF_SHA
ota=next(e['data'] for e in parse_ufw(source.read_bytes())['entries'] if e['name']=='ota.bin')
body=ota[32:]
assert len(body)==6898 and hashlib.sha256(body).hexdigest()==BODY_SHA
header=root/'firmware/b1_pinned_loader.h'
lines=['/* Auto-generated by tools/generate_pinned_loader.py from BEETLE RC1.01; GPL-3.0. */',
       '#ifndef B1_PINNED_LOADER_H', '#define B1_PINNED_LOADER_H',
       'static const unsigned char b1_trusted_loader[6898] = {']
for off in range(0,len(body),16):
    lines.append('    '+','.join('0x%02x'%v for v in body[off:off+16])+',')
lines+=['};','#endif']
header.write_text('\n'.join(lines)+'\n')
print('Generated',header,'len',len(body),'sha256',BODY_SHA)
